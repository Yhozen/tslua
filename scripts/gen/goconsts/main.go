// Command goconsts dumps the constants (enums, flags) of typescript-go
// packages into Lua modules, so the Lua port uses exactly the upstream values.
//
// Usage: go run . <typescript-go dir> <out dir> <pkg patterns...>
package main

import (
	"fmt"
	"go/constant"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"
)

type entry struct {
	name, typ, lit string
	line          int
	file          string
}

func luaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '\n':
			b.WriteString("\\n")
		case c < 0x20 || c >= 0x7f:
			fmt.Fprintf(&b, "\\%03d", c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func main() {
	root, outDir := os.Args[1], os.Args[2]
	cfg := &packages.Config{Mode: packages.NeedTypes | packages.NeedName | packages.NeedFiles, Dir: root}
	pkgs, err := packages.Load(cfg, os.Args[3:]...)
	if err != nil {
		panic(err)
	}
	for _, p := range pkgs {
		for _, e := range p.Errors {
			fmt.Fprintln(os.Stderr, e)
		}
		var entries []entry
		sc := p.Types.Scope()
		for _, n := range sc.Names() {
			c, ok := sc.Lookup(n).(*types.Const)
			if !ok {
				continue
			}
			v := c.Val()
			var lit string
			switch v.Kind() {
			case constant.String:
				lit = luaString(constant.StringVal(v))
			case constant.Bool:
				lit = v.ExactString()
			case constant.Int:
				if i, ok := constant.Int64Val(v); ok {
					lit = strconv.FormatInt(i, 10)
				} else if u, ok := constant.Uint64Val(v); ok {
					lit = fmt.Sprintf("0x%x", u) // wraps to a negative Lua integer, same bits
				} else {
					continue
				}
			case constant.Float:
				f, _ := constant.Float64Val(v)
				lit = strconv.FormatFloat(f, 'g', -1, 64)
				if !strings.ContainsAny(lit, ".e") {
					lit += ".0"
				}
			default:
				continue
			}
			typ := ""
			if named, ok := c.Type().(*types.Named); ok && named.Obj().Pkg() == p.Types {
				typ = named.Obj().Name()
			}
			pos := p.Fset.Position(c.Pos())
			entries = append(entries, entry{n, typ, lit, pos.Line, filepath.Base(pos.Filename)})
		}
		sort.SliceStable(entries, func(i, j int) bool {
			if entries[i].file != entries[j].file {
				return entries[i].file < entries[j].file
			}
			return entries[i].line < entries[j].line
		})
		rel := strings.TrimPrefix(p.PkgPath, "github.com/microsoft/typescript-go/internal/")
		var b strings.Builder
		b.WriteString("-- Code generated by scripts/gen/goconsts from typescript-go internal/" + rel + ". DO NOT EDIT.\n")
		b.WriteString("-- Typed constants are grouped by Go type with the type-name prefix removed\n")
		b.WriteString("-- (ast.KindIdentifier -> Kind.Identifier). Untyped/foreign-typed constants keep\n")
		b.WriteString("-- their Go name at the top level. Each enum also has a <Type>_names reverse map.\n")
		b.WriteString("local M = {}\n\n")
		var order []string
		groups := map[string][]entry{}
		for _, e := range entries {
			if e.typ == "" {
				fmt.Fprintf(&b, "M.%s = %s\n", e.name, e.lit)
				continue
			}
			if _, ok := groups[e.typ]; !ok {
				order = append(order, e.typ)
			}
			groups[e.typ] = append(groups[e.typ], e)
		}
		for _, t := range order {
			fmt.Fprintf(&b, "\nM.%s = {\n", t)
			for _, e := range groups[t] {
				key := strings.TrimPrefix(e.name, t)
				if key == "" || !(key[0] >= 'A' && key[0] <= 'Z' || key[0] == '_') {
					key = e.name
				}
				fmt.Fprintf(&b, "    %s = %s,\n", key, e.lit)
			}
			b.WriteString("}\n")
			fmt.Fprintf(&b, "M.%s_names = {}\n", t)
			fmt.Fprintf(&b, "for _, k in ipairs({")
			for i, e := range groups[t] {
				if i > 0 {
					b.WriteString(", ")
				}
				key := strings.TrimPrefix(e.name, t)
				if key == "" || !(key[0] >= 'A' && key[0] <= 'Z' || key[0] == '_') {
					key = e.name
				}
				b.WriteString(luaString(key))
			}
			fmt.Fprintf(&b, "}) do\n    local v = M.%s[k]\n    if M.%s_names[v] == nil then\n        M.%s_names[v] = k\n    end\nend\n", t, t, t)
		}
		b.WriteString("\nreturn M\n")
		dir := filepath.Join(outDir, filepath.FromSlash(rel))
		if err := os.MkdirAll(dir, 0o755); err != nil {
			panic(err)
		}
		if err := os.WriteFile(filepath.Join(dir, "consts_generated.lua"), []byte(b.String()), 0o644); err != nil {
			panic(err)
		}
	}
}
