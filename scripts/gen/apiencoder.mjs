// Translates the generated Go files of internal/api/encoder (encoder_generated.go,
// decoder_generated.go, produced upstream by _scripts/generate-encoder.ts) into Lua.
// The Go files are regular enough (switch-on-kind dispatch, factory calls, bit packing) that a
// line-based translation is exact. Usage: node scripts/gen/apiencoder.mjs [vendor/typescript-go]
import fs from "node:fs";
import path from "node:path";

const upstream = process.argv[2] ?? "vendor/typescript-go";
const srcDir = path.join(upstream, "internal/api/encoder");
const outDir = "src/tslua/api/encoder";

const packageFuncs = new Set([
    "boolToByte",
    "hasModifiers",
    "newChildIter",
    "getNodeCommonData_SyntheticExpression",
    "decodeNodeCommonData_SyntheticExpression",
]);
const methodReceivers = new Set(["d", "it", "strs"]);

function lowerCamel(name) {
    const m = /^[A-Z]+/.exec(name);
    if (!m) return name;
    let run = m[0];
    if (run.length > 1 && run.length < name.length && /[a-z]/.test(name[run.length])) {
        run = run.slice(0, -1);
    }
    return run.toLowerCase() + name.slice(run.length);
}

// Index of the ")" matching the "(" at i.
function matchParen(s, i) {
    let depth = 0;
    for (let j = i; j < s.length; j++) {
        if (s[j] === "(") depth++;
        else if (s[j] === ")") {
            depth--;
            if (depth === 0) return j;
        }
    }
    throw new Error("unbalanced parens: " + s);
}

// Removes Go conversions like uint32(x) -> (x).
function stripConversions(s) {
    const re = /\b(uint32|uint8|int|ast\.TokenFlags|ast\.Kind|ast\.NodeFlags)\(/g;
    let m;
    while ((m = re.exec(s))) {
        const open = m.index + m[0].length - 1;
        const close = matchParen(s, open);
        const inner = s.slice(open + 1, close);
        const simple = /^[\w.]+(\(\))?$/.test(inner);
        s = s.slice(0, m.index) + (simple ? inner : "(" + inner + ")") + s.slice(close + 1);
        re.lastIndex = m.index;
    }
    return s;
}

function expr(s) {
    s = s.trim();
    // fmt.Errorf / fmt.Sprintf with %v of a Kind and %d of an int.
    s = s.replace(/fmt\.(Errorf|Sprintf)\("([^"]*)"((?:, [^,()]+(?:\([^()]*\))?)*)\)/g, (_, _fn, fmtStr, args) => {
        const argList = args ? args.slice(2).split(", ") : [];
        const parts = fmtStr.split(/(%v|%d)/);
        const out = [];
        let ai = 0;
        for (const p of parts) {
            if (p === "%v") out.push(`ast.Kind_String(${expr(argList[ai++])})`);
            else if (p === "%d") out.push(`tostring(${expr(argList[ai++])})`);
            else if (p !== "") out.push(JSON.stringify(p));
        }
        return out.join(" .. ");
    });
    s = stripConversions(s);
    s = s.replace(/\[\]string\{(\w+)\}/g, "{ $1 }");
    s = s.replace(/\blen\((\w+)\)/g, "#$1");
    s = s.replace(/\blen\((\w+\.\w+)\)/g, "core.Len($1)");
    s = s.replace(/\*extendedData\b/g, "extendedData");
    s = s.replace(/\bnode\.As\w+\(\)\.Text\(\)/g, "node:Text()");
    s = s.replace(/\bnode\.As\w+\(\)\.Text\b/g, "node.text");
    s = s.replace(/\bast\.Kind([A-Z]\w*)/g, "Kind.$1");
    s = s.replace(/\b(NodeDataType\w+|NodeData\w+Mask|SyntaxKindNodeList)\b/g, "encoder.$1");
    // index adjustments for 0-based Go indices into 1-based Lua arrays
    s = s.replace(/\bchildIndices\[0\]/g, "childIndices[1]");
    s = s.replace(/\bd\.nodes\[(\w+)\]/g, "d.nodes[$1 + 1]");
    s = s.replace(/\bd\.nodeLists\[(\w+)\]/g, "d.nodeLists[$1 + 1]");
    // selectors: methods and fields
    s = s.replace(/(?<=[\w)])\.([A-Za-z_]\w*)(\(?)/g, (all, name, paren, offset, whole) => {
        const recv = /(\w+)$/.exec(whole.slice(0, offset))?.[1] ?? ")";
        if (recv === "encoder" || recv === "Kind" || recv === "ast" || recv === "core") return all;
        if (paren) {
            if (/^[A-Z]/.test(name) || methodReceivers.has(recv)) return `:${name}(`;
            return all;
        }
        if (/^[A-Z]/.test(name)) return `.${lowerCamel(name)}`;
        return all;
    });
    s = s.replace(/(?<![.:\w])(\w+)\(/g, (all, name) => {
        if (packageFuncs.has(name) || /^recordExtendedData_/.test(name)) return `encoder.${name}(`;
        return all;
    });
    s = s.replace(/!=/g, "~=");
    s = s.replace(/&&/g, "and");
    s = s.replace(/\|\|/g, "or");
    s = s.replace(/!(?!=)/g, "not ");
    return s;
}

function params(p) {
    if (!p.trim()) return "";
    return p.split(",").map(x => x.trim().split(/\s+/)[0]).join(", ");
}

function translate(goFile, luaFile, header) {
    const lines = fs.readFileSync(path.join(srcDir, goFile), "utf8").split("\n");
    const out = [
        `-- Code generated by scripts/gen/apiencoder.mjs from internal/api/encoder/${goFile}. DO NOT EDIT.`,
        ...header,
    ];
    const stack = [];
    let indent = 0;
    const emit = s => out.push("    ".repeat(indent) + s);
    let i = 0;
    // skip package/import header
    while (i < lines.length && !lines[i].startsWith("func ")) i++;
    for (; i < lines.length; i++) {
        let line = lines[i].trim();
        if (line === "" || line.startsWith("//")) {
            if (line.startsWith("//")) emit("--" + line.slice(2));
            continue;
        }
        let m;
        if ((m = /^func \(d \*astDecoder\) (\w+)\((.*?)\)(.*)\{$/.exec(line))) {
            out.push("");
            emit(`function astDecoder:${m[1]}(${params(m[2])})`);
            stack.push({ type: "func" });
            indent++;
            emit("local d = self");
            continue;
        }
        if ((m = /^func (\w+)\((.*?)\)(.*)\{$/.exec(line))) {
            out.push("");
            emit(`function encoder.${m[1]}(${params(m[2])})`);
            stack.push({ type: "func" });
            indent++;
            continue;
        }
        if ((m = /^switch (.*) \{$/.exec(line))) {
            const subj = expr(m[1]);
            const local = /^[\w.]+$/.test(subj) ? subj : null;
            if (!local) {
                emit(`local switchValue = ${subj}`);
            }
            stack.push({ type: "switch", subj: local ?? "switchValue", first: true });
            continue;
        }
        if (line.startsWith("case ") || line === "default:") {
            const sw = stack[stack.length - 1];
            if (sw.type === "case") {
                stack.pop();
                indent--;
            }
            const top = stack[stack.length - 1];
            if (top.type !== "switch") throw new Error("case outside switch at line " + (i + 1));
            if (line === "default:") {
                emit("else");
            } else {
                let text = line.slice(5);
                while (!text.endsWith(":")) {
                    i++;
                    text += " " + lines[i].trim();
                }
                text = text.slice(0, -1);
                const values = text.split(",").map(v => v.trim()).filter(Boolean).map(expr);
                const conds = values.map(v => `${top.subj} == ${v}`);
                let cond;
                if (conds.length <= 4) {
                    cond = conds.join(" or ");
                } else {
                    cond = conds.join(" or\n" + "    ".repeat(indent + 1));
                }
                emit(`${top.first ? "if" : "elseif"} ${cond} then`);
            }
            top.first = false;
            stack.push({ type: "case" });
            indent++;
            continue;
        }
        if (line === "}") {
            let top = stack.pop();
            if (top.type === "case") {
                indent--;
                top = stack.pop();
                if (top.type !== "switch") throw new Error("bad nesting at line " + (i + 1));
                emit("end");
                continue;
            }
            if (top.type === "switch") {
                if (!top.first) emit("end");
                continue;
            }
            indent--;
            emit("end");
            continue;
        }
        if ((m = /^if (.*) \{$/.exec(line))) {
            emit(`if ${expr(m[1])} then`);
            stack.push({ type: "if" });
            indent++;
            continue;
        }
        if ((m = /^for (\w+), (\w+) := range (\w+) \{$/.exec(line))) {
            emit(`for ${m[1]}, ${m[2]} in ipairs(${m[3]}) do`);
            stack.push({ type: "for" });
            indent++;
            continue;
        }
        if ((m = /^var (\w+) (.*)$/.exec(line))) {
            const t = m[2];
            let zero = "";
            if (t === "uint32" || t === "uint8" || t === "int") zero = " = 0";
            else if (t === "ast.Kind") zero = " = Kind.Unknown";
            emit(`local ${m[1]}${zero}`);
            continue;
        }
        if ((m = /^offset := uint32\(len\(\*extendedData\)\)$/.exec(line))) {
            emit("local offset = #extendedData * 4");
            continue;
        }
        if ((m = /^([\w, ]+) := (.*)$/.exec(line))) {
            let rhs = expr(m[2]);
            if (/^node\.As\w+\(\)$/.test(m[2])) rhs = "node";
            emit(`local ${m[1]} = ${rhs}`);
            continue;
        }
        if ((m = /^return (.*)$/.exec(line))) {
            emit(`return ${expr(m[1])}`);
            continue;
        }
        if ((m = /^panic\((.*)\)$/.exec(line))) {
            emit(`error(${expr(m[1])}, 0)`);
            continue;
        }
        if ((m = /^nodes\[i\] = (.*)$/.exec(line))) {
            // Go indexes a slice (panicking when out of range); Lua arrays are 1-based.
            emit(`encoder.sliceStore(nodes, i - 1, ${expr(m[1])})`);
            continue;
        }
        if ((m = /^([\w.\[\]]+) = (.*)$/.exec(line))) {
            emit(`${expr(m[1])} = ${expr(m[2])}`);
            continue;
        }
        if (/^[\w.]+\(.*\)$/.test(line)) {
            emit(expr(line));
            continue;
        }
        throw new Error(`untranslated line ${i + 1} of ${goFile}: ${line}`);
    }
    fs.writeFileSync(path.join(outDir, luaFile), out.join("\n") + "\n");
}

translate("encoder_generated.go", "encoder_generated.lua", [
    'local encoder = require("tslua.api.encoder")',
    'local ast = require("tslua.ast")',
    'local core = require("tslua.core")',
    "",
    "local Kind = ast.Kind",
]);
translate("decoder_generated.go", "decoder_generated.lua", [
    'local encoder = require("tslua.api.encoder")',
    'local ast = require("tslua.ast")',
    "",
    "local Kind = ast.Kind",
    "local astDecoder = encoder.astDecoder",
]);
