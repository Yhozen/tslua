// Generates src/tslua/stringutil/identifier_parts_generated.lua and
// src/tslua/stringutil/js_case_generated.lua from typescript-go's
// internal/stringutil/{identifier_parts_generated.go,js_case_generated.go}.
// Usage: node scripts/gen/stringutil.mjs [typescript-go dir] [output dir]
import fs from "node:fs";
import path from "node:path";

const root = process.argv[2] ?? "vendor/typescript-go";
const outDir = process.argv[3] ?? "src/tslua/stringutil";
const srcDir = path.join(root, "internal/stringutil");

// Parses `var <name> = &unicode.RangeTable{ R16: [...], R32: [...], LatinOffset: n }`.
function parseRangeTables(src) {
    const tables = [];
    const re = /^var (\w+) = &unicode\.RangeTable\{([\s\S]*?)^\}/gm;
    let m;
    while ((m = re.exec(src))) {
        const [, name, body] = m;
        const ranges = [];
        const rre = /\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+), (\d+)\}/g;
        let r;
        while ((r = rre.exec(body))) {
            ranges.push([parseInt(r[1], 16), parseInt(r[2], 16), parseInt(r[3], 10)]);
        }
        const lo = /LatinOffset: (\d+)/.exec(body);
        tables.push({ name, ranges, latinOffset: lo ? parseInt(lo[1], 10) : 0 });
    }
    return tables;
}

function hex(n) {
    return "0x" + n.toString(16).toUpperCase();
}

function emitRangeTable(t) {
    let out = `-- ${t.ranges.length} ranges as flat (lo, hi, stride) triples, sorted by lo.\n`;
    out += `stringutil.${t.name} = {\n`;
    for (let i = 0; i < t.ranges.length; i += 4) {
        const chunk = t.ranges.slice(i, i + 4).map(([lo, hi, st]) => `${hex(lo)}, ${hex(hi)}, ${st},`);
        out += "    " + chunk.join(" ") + "\n";
    }
    out += "}\n";
    return out;
}

// Decodes a Go interpreted string literal body (only the escapes the generator emits).
function goString(lit) {
    let s = "";
    for (let i = 0; i < lit.length; i++) {
        const c = lit[i];
        if (c !== "\\") {
            s += c;
            continue;
        }
        const e = lit[++i];
        if (e === "u") {
            s += String.fromCodePoint(parseInt(lit.slice(i + 1, i + 5), 16));
            i += 4;
        } else if (e === "U") {
            s += String.fromCodePoint(parseInt(lit.slice(i + 1, i + 9), 16));
            i += 8;
        } else if (e === "\\" || e === '"') {
            s += e;
        } else {
            throw new Error("unsupported escape \\" + e);
        }
    }
    return s;
}

// Lua string literal with \u{...} escapes for everything outside printable ASCII.
function luaString(s) {
    let out = '"';
    for (const ch of s) {
        const cp = ch.codePointAt(0);
        if (ch === '"' || ch === "\\") out += "\\" + ch;
        else if (cp >= 0x20 && cp < 0x7f) out += ch;
        else out += "\\u{" + cp.toString(16).toUpperCase() + "}";
    }
    return out + '"';
}

const header = (from) =>
    `-- Code generated by scripts/gen/stringutil.mjs from typescript-go internal/stringutil/${from}. DO NOT EDIT.\n` +
    `local stringutil = require("tslua.stringutil")\n\n`;

// identifier_parts_generated.go
{
    const src = fs.readFileSync(path.join(srcDir, "identifier_parts_generated.go"), "utf8");
    const tables = parseRangeTables(src);
    if (tables.length !== 2) throw new Error("expected 2 range tables in identifier_parts_generated.go");
    let out = header("identifier_parts_generated.go");
    const comment = src.split("\n").slice(1).filter(l => l.startsWith("//")).map(l => "--" + l.slice(2)).join("\n");
    out += comment + "\n\n";
    for (const t of tables) out += emitRangeTable(t) + "\n";
    fs.writeFileSync(path.join(outDir, "identifier_parts_generated.lua"), out.trimEnd() + "\n");
}

// js_case_generated.go
{
    const src = fs.readFileSync(path.join(srcDir, "js_case_generated.go"), "utf8");
    let out = header("js_case_generated.go");
    const comment = src.split("\n").slice(1).filter(l => l.startsWith("//")).map(l => "--" + l.slice(2)).join("\n");
    out += comment + "\n\n";
    out += "stringutil.specialCasingConditionNone = 0\n";
    out += "stringutil.specialCasingConditionFinalSigma = 1\n\n";
    out += "-- specialCasingMapping: { lower = string, upper = string, conditionalLower = string, condition = int }\n";
    out += "local None = stringutil.specialCasingConditionNone\n";
    out += "local FinalSigma = stringutil.specialCasingConditionFinalSigma\n";
    out += "stringutil.specialCasingMappings = {\n";
    const start = src.indexOf("var specialCasingMappings");
    const end = src.indexOf("\n}\n", start);
    const body = src.slice(start, end);
    const mre = /^\s*(0x[0-9A-Fa-f]+):\s*\{(.*)\},$/gm;
    let m, count = 0;
    while ((m = mre.exec(body))) {
        const fields = [];
        const fre = /(\w+): ("(?:[^"\\]|\\.)*"|\w+)/g;
        let f;
        while ((f = fre.exec(m[2]))) {
            const [, k, v] = f;
            if (k === "condition") {
                if (v === "specialCasingConditionNone") fields.push("condition = None");
                else if (v === "specialCasingConditionFinalSigma") fields.push("condition = FinalSigma");
                else throw new Error("unknown condition " + v);
            } else {
                fields.push(`${k} = ${luaString(goString(v.slice(1, -1)))}`);
            }
        }
        if (!fields.some(f => f.startsWith("conditionalLower"))) fields.splice(2, 0, 'conditionalLower = ""');
        out += `    [${hex(parseInt(m[1], 16))}] = { ${fields.join(", ")} },\n`;
        count++;
    }
    if (count === 0) throw new Error("no specialCasingMappings parsed");
    out += "}\n\n";
    const tables = parseRangeTables(src);
    if (tables.length !== 2) throw new Error("expected 2 range tables in js_case_generated.go");
    for (const t of tables) out += emitRangeTable(t) + "\n";
    fs.writeFileSync(path.join(outDir, "js_case_generated.lua"), out.trimEnd() + "\n");
}
