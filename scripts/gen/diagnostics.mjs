// Generates src/tslua/diagnostics/messages_generated.lua from typescript-go's
// internal/diagnostics/diagnostics_generated.go.
// Usage: node scripts/gen/diagnostics.mjs <typescript-go dir>
import fs from "node:fs";
import path from "node:path";

const root = process.argv[2] ?? "vendor/typescript-go";
const src = fs.readFileSync(path.join(root, "internal/diagnostics/diagnostics_generated.go"), "utf8");
const re = /^var (\w+) = &Message\{(.*)\}$/gm;
const lua = s => JSON.stringify(s).replace(/\\u([0-9a-f]{4})/g, (_, h) => {
    const cp = parseInt(h, 16);
    return Buffer.from(String.fromCodePoint(cp)).toString("binary").split("").map(c => "\\" + c.charCodeAt(0)).join("");
});
let out = "-- Code generated by scripts/gen/diagnostics.mjs. DO NOT EDIT.\n";
out += "-- Mirrors typescript-go internal/diagnostics/diagnostics_generated.go.\nreturn function(M, Message, Category)\n";
let m, n = 0;
while ((m = re.exec(src))) {
    const [, name, body] = m;
    const fields = [];
    const fre = /(\w+): ("(?:[^"\\]|\\.)*"|\w+)/g;
    let f;
    while ((f = fre.exec(body))) {
        let [, k, v] = f;
        if (k === "category") v = "Category." + v.replace(/^Category/, "");
        else if (v.startsWith('"')) v = lua(JSON.parse(v));
        fields.push(`${k} = ${v}`);
    }
    out += `    M.${name} = Message.new({ ${fields.join(", ")} })\n`;
    n++;
}
out += "end\n";
fs.mkdirSync("src/tslua/diagnostics", { recursive: true });
fs.writeFileSync("src/tslua/diagnostics/messages_generated.lua", out);
console.log(`wrote ${n} messages`);
