// Command loctables writes the localization data of the Lua port:
//
//   - src/tslua/diagnostics/loc/<var>.lua: the localized diagnostic message tables, read from the
//     same locale .json.gz files that internal/diagnostics/loc_generated.go embeds;
//   - src/tslua/diagnostics/loc_generated.lua: the port of loc_generated.go (matcher, localeFuncs);
//   - src/tslua/locale/language_generated.lua: the golang.org/x/text/language data the Lua
//     emulation of language.Parse and Matcher.Match needs (canonical language subtags, and the
//     match results of the loc_generated.go matcher for every language, language-region and
//     language-script combination).
//
// Usage: go run . <typescript-go dir> <src/tslua dir>
package main

import (
	"compress/gzip"
	"encoding/json"
	"fmt"
	"io"
	"log"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"golang.org/x/text/language"
)

type localeInfo struct {
	tag     string // e.g. "zh-CN"
	varName string // e.g. "zhCN"
	file    string // e.g. "loc/zh-CN.json.gz"
}

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: go run . <typescript-go dir> <src/tslua dir>")
	}
	upstream, out := os.Args[1], os.Args[2]
	diagDir := filepath.Join(upstream, "internal", "diagnostics")

	src, err := os.ReadFile(filepath.Join(diagDir, "loc_generated.go"))
	if err != nil {
		log.Fatal(err)
	}
	text := string(src)

	// The matcher's supported tags, in order (index 0 is English).
	matcherStart := strings.Index(text, "language.NewMatcher(")
	matcherEnd := strings.Index(text[matcherStart:], "})") + matcherStart
	tags := []string{"en"}
	for _, m := range regexp.MustCompile(`language\.MustParse\("([^"]+)"\)`).FindAllStringSubmatch(text[matcherStart:matcherEnd], -1) {
		tags = append(tags, m[1])
	}
	// localeFuncs, in order (nil for English).
	funcsStart := strings.Index(text, "var localeFuncs")
	funcsEnd := strings.Index(text[funcsStart:], "\n}") + funcsStart
	var funcs []string
	for _, line := range strings.Split(text[funcsStart:funcsEnd], "\n")[1:] {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		name := strings.TrimSuffix(strings.Fields(line)[0], ",")
		funcs = append(funcs, name)
	}
	// //go:embed loc/<file>\nvar <var>Data string
	embeds := map[string]string{}
	for _, m := range regexp.MustCompile(`//go:embed (\S+)\nvar (\w+)Data string`).FindAllStringSubmatch(text, -1) {
		embeds[m[2]] = m[1]
	}
	var locales []localeInfo
	for i, f := range funcs {
		if f == "nil" {
			continue
		}
		file, ok := embeds[f]
		if !ok {
			log.Fatalf("no embed for %s", f)
		}
		locales = append(locales, localeInfo{tag: tags[i], varName: f, file: file})
	}

	for _, l := range locales {
		writeLocaleData(diagDir, out, l)
	}
	writeLocGenerated(out, tags, funcs)
	writeLanguageData(out, tags)
}

func luaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"':
			b.WriteString(`\"`)
		case c == '\\':
			b.WriteString(`\\`)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\r':
			b.WriteString(`\r`)
		case c == '\t':
			b.WriteString(`\t`)
		case c < 0x20 || c == 0x7f:
			fmt.Fprintf(&b, `\%03d`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func writeFile(path string, content string) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeLocaleData(diagDir string, out string, l localeInfo) {
	f, err := os.Open(filepath.Join(diagDir, l.file))
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	gr, err := gzip.NewReader(f)
	if err != nil {
		log.Fatal(err)
	}
	data, err := io.ReadAll(gr)
	if err != nil {
		log.Fatal(err)
	}
	var messages map[string]string
	if err := json.Unmarshal(data, &messages); err != nil {
		log.Fatal(err)
	}
	keys := make([]string, 0, len(messages))
	for k := range messages {
		keys = append(keys, k)
	}
	slices.Sort(keys)

	var b strings.Builder
	fmt.Fprintf(&b, "-- Code generated by scripts/gen/loctables from internal/diagnostics/%s; DO NOT EDIT.\n", l.file)
	b.WriteString("return {\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "    [%s] = %s,\n", luaString(k), luaString(messages[k]))
	}
	b.WriteString("}\n")
	writeFile(filepath.Join(out, "diagnostics", "loc", l.varName+".lua"), b.String())
}

func writeLocGenerated(out string, tags []string, funcs []string) {
	var b strings.Builder
	b.WriteString("-- Code generated by scripts/gen/loctables from internal/diagnostics/loc_generated.go; DO NOT EDIT.\n")
	b.WriteString("local diagnostics = require(\"tslua.diagnostics\")\n")
	b.WriteString("local locale = require(\"tslua.locale\")\n\n")
	b.WriteString("-- sync.OnceValue\nlocal function onceValue(f)\n    local value = nil\n    return function()\n        if f ~= nil then\n            value = f()\n            f = nil\n        end\n        return value\n    end\nend\n\n")
	b.WriteString("diagnostics.matcher = locale.NewMatcher({\n")
	for _, t := range tags {
		fmt.Fprintf(&b, "    %s,\n", luaString(t))
	}
	b.WriteString("})\n\n")
	b.WriteString("-- Go []func() map[Key]string; false stands for Go's nil entry (English, the default).\n")
	b.WriteString("diagnostics.localeFuncs = {\n")
	for _, f := range funcs {
		if f == "nil" {
			b.WriteString("    false, -- English (default)\n")
		} else {
			fmt.Fprintf(&b, "    function() return diagnostics.%s() end,\n", f)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("-- The locale data is a generated Lua table (Go embeds a gzipped JSON object).\n")
	b.WriteString("function diagnostics.loadLocaleData(data)\n")
	b.WriteString("    return require(\"tslua.diagnostics.loc.\" .. data)\n")
	b.WriteString("end\n")
	for _, f := range funcs {
		if f == "nil" {
			continue
		}
		fmt.Fprintf(&b, "\ndiagnostics.%s = onceValue(function()\n    return diagnostics.loadLocaleData(%s)\nend)\n", f, luaString(f))
	}
	writeFile(filepath.Join(out, "diagnostics", "loc_generated.lua"), b.String())
}

type result struct {
	index int
	conf  language.Confidence
}

func effective(r result) result {
	if r.conf < language.Low {
		return result{0, language.No}
	}
	return r
}

func writeLanguageData(out string, tags []string) {
	supported := make([]language.Tag, len(tags))
	for i, t := range tags {
		if i == 0 {
			supported[i] = language.English
		} else {
			supported[i] = language.MustParse(t)
		}
	}
	matcher := language.NewMatcher(supported)
	match := func(s string) (result, bool) {
		tag, err := language.Parse(s)
		if err != nil {
			return result{}, false
		}
		_, index, conf := matcher.Match(tag)
		return effective(result{index, conf}), true
	}

	letters := "abcdefghijklmnopqrstuvwxyz"
	var candidates []string
	for _, x := range letters {
		for _, y := range letters {
			candidates = append(candidates, string(x)+string(y))
			for _, z := range letters {
				candidates = append(candidates, string(x)+string(y)+string(z))
			}
		}
	}
	slices.Sort(candidates)

	// Language subtags that language.Parse canonicalizes (e.g. "ces" -> "cs", "iw" -> "he",
	// "sh" -> "sr-Latn"), and the set of accepted canonical languages.
	aliases := map[string]string{}
	var valid []string
	var langs []string
	seen := map[string]bool{}
	for _, c := range candidates {
		tag, err := language.Parse(c)
		if err != nil {
			continue
		}
		valid = append(valid, c)
		canonical := tag.String()
		if canonical != c {
			aliases[c] = canonical
		}
		base, _ := tag.Base()
		if !seen[base.String()] {
			seen[base.String()] = true
			langs = append(langs, base.String())
		}
	}
	slices.Sort(langs)

	var regions []string
	var validRegions []string
	regionAliases := map[string]string{}
	addRegion := func(r string) {
		if _, err := language.ParseRegion(r); err != nil {
			return
		}
		validRegions = append(validRegions, r)
		tag, err := language.Parse("en-" + r)
		if err != nil {
			log.Fatal(err)
		}
		reg, _ := tag.Region()
		if reg.String() == r {
			regions = append(regions, r)
		} else {
			regionAliases[r] = reg.String()
		}
	}
	for _, x := range strings.ToUpper(letters) {
		for _, y := range strings.ToUpper(letters) {
			addRegion(string(x) + string(y))
		}
	}
	for n := 0; n < 1000; n++ {
		addRegion(fmt.Sprintf("%03d", n))
	}
	var scripts []string
	upper := strings.ToUpper(letters)
	for _, a := range upper {
		for _, b := range letters {
			for _, c := range letters {
				for _, d := range letters {
					s := string(a) + string(b) + string(c) + string(d)
					if sc, err := language.ParseScript(s); err == nil && sc.String() == s {
						scripts = append(scripts, s)
					}
				}
			}
		}
	}

	base := map[string]result{}
	var b strings.Builder
	b.WriteString("-- Code generated by scripts/gen/loctables from golang.org/x/text/language; DO NOT EDIT.\n")
	b.WriteString("-- aliases: language subtags that language.Parse rewrites, with their canonical tag.\n")
	b.WriteString("-- matches: results of the diagnostics matcher (internal/diagnostics/loc_generated.go) with\n")
	b.WriteString("-- confidence >= Low, as { index, confidence }, keyed by language, language-REGION (only where the\n")
	b.WriteString("-- region changes the matched index; { 0, 0 } means no match) and language-Script (no entry: no\n")
	b.WriteString("-- match). Regions that only lower the confidence (e.g. de-AT: High instead of Exact) are omitted.\n")
	b.WriteString("-- languages, scripts, regions, variants: the registered subtags language.Parse accepts\n")
	b.WriteString("-- (variants in the order Tag.String() sorts them).\n")
	b.WriteString("-- regionAliases: region subtags that language.Parse rewrites.\n")
	b.WriteString("local M = {}\n\n")
	writeList := func(name string, items []string) {
		fmt.Fprintf(&b, "M.%s = [[\n", name)
		for i, it := range items {
			if i > 0 {
				if i%16 == 0 {
					b.WriteString("\n")
				} else {
					b.WriteString(" ")
				}
			}
			b.WriteString(it)
		}
		b.WriteString("\n]]\n\n")
	}
	writeList("languages", valid)
	writeList("scripts", scripts)
	writeList("regions", validRegions)
	writeList("variants", readVariants())
	b.WriteString("M.regionAliases = {\n")
	for _, k := range slices.Sorted(maps.Keys(regionAliases)) {
		fmt.Fprintf(&b, "    [%s] = %s,\n", luaString(k), luaString(regionAliases[k]))
	}
	b.WriteString("}\n\nM.aliases = {\n")
	aliasKeys := make([]string, 0, len(aliases))
	for k := range aliases {
		aliasKeys = append(aliasKeys, k)
	}
	slices.Sort(aliasKeys)
	for _, k := range aliasKeys {
		fmt.Fprintf(&b, "    [%s] = %s,\n", luaString(k), luaString(aliases[k]))
	}
	b.WriteString("}\n\nM.matches = {\n")
	write := func(key string, r result) {
		fmt.Fprintf(&b, "    [%s] = { %d, %d },\n", luaString(key), r.index, int(r.conf))
	}
	for _, l := range langs {
		r, ok := match(l)
		if !ok {
			continue
		}
		base[l] = r
		if r.conf >= language.Low {
			write(l, r)
		}
	}
	for _, l := range langs {
		bl, ok := base[l]
		if !ok {
			continue
		}
		for _, reg := range regions {
			r, ok := match(l + "-" + reg)
			if ok && r.index != bl.index {
				write(l+"-"+reg, r)
			}
		}
		for _, sc := range scripts {
			r, ok := match(l + "-" + sc)
			if ok && r.conf >= language.Low {
				write(l+"-"+sc, r)
			}
		}
	}
	b.WriteString("}\n\nreturn M\n")
	writeFile(filepath.Join(out, "locale", "language_generated.lua"), b.String())
}

// readVariants returns the registered variant subtags (golang.org/x/text/internal/language
// variantIndex), in index order.
func readVariants() []string {
	dir, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/text").Output()
	if err != nil {
		log.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(dir)), "internal", "language", "tables.go"))
	if err != nil {
		log.Fatal(err)
	}
	text := string(src)
	start := strings.Index(text, "var variantIndex = map[string]uint8{")
	end := strings.Index(text[start:], "\n}") + start
	index := map[string]int64{}
	var variants []string
	for _, m := range regexp.MustCompile(`"([0-9a-z]+)":\s*0x([0-9a-f]+),`).FindAllStringSubmatch(text[start:end], -1) {
		n, err := strconv.ParseInt(m[2], 16, 64)
		if err != nil {
			log.Fatal(err)
		}
		index[m[1]] = n
		variants = append(variants, m[1])
	}
	// in variantIndex order, which is the order Tag.String() lists variants in
	slices.SortFunc(variants, func(a, b string) int { return int(index[a] - index[b]) })
	return variants
}
