// Command regexptables writes the Go unicode tables the Lua port of the standard library
// regexp package (src/tslua/regexp) needs: unicode.Categories, Scripts, CategoryAliases,
// FoldCategory, FoldScript and Cn as range tables, plus the precomputed results of
// unicode.SimpleFold, IsPrint, IsLetter and IsDigit over all runes.
//
// Usage: go run . <out.lua>
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"unicode"
)

func luaString(s string) string {
	return fmt.Sprintf("%q", s) // table names are ASCII identifiers
}

func writeTable(b *strings.Builder, t *unicode.RangeTable) {
	b.WriteString("{ r16 = {")
	for i, r := range t.R16 {
		if i > 0 {
			b.WriteString(",")
		}
		fmt.Fprintf(b, " 0x%x, 0x%x, %d", r.Lo, r.Hi, r.Stride)
	}
	b.WriteString(" }, r32 = {")
	for i, r := range t.R32 {
		if i > 0 {
			b.WriteString(",")
		}
		fmt.Fprintf(b, " 0x%x, 0x%x, %d", r.Lo, r.Hi, r.Stride)
	}
	b.WriteString(" } }")
}

func writeTables(b *strings.Builder, name string, m map[string]*unicode.RangeTable) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "\nM.%s = {\n", name)
	for _, k := range keys {
		fmt.Fprintf(b, "    [%s] = ", luaString(k))
		writeTable(b, m[k])
		b.WriteString(",\n")
	}
	b.WriteString("}\n")
}

// writeRanges writes the runes for which pred holds as a flat list of lo, hi pairs.
func writeRanges(b *strings.Builder, name string, pred func(rune) bool) {
	fmt.Fprintf(b, "\nM.%s = {", name)
	n := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !pred(r) {
			continue
		}
		lo := r
		for r+1 <= unicode.MaxRune && pred(r+1) {
			r++
		}
		if n%8 == 0 {
			b.WriteString("\n   ")
		}
		fmt.Fprintf(b, " 0x%x, 0x%x,", lo, r)
		n++
	}
	b.WriteString("\n}\n")
}

func main() {
	var b strings.Builder
	b.WriteString("-- Code generated by scripts/gen/regexptables from Go unicode " + unicode.Version + ". DO NOT EDIT.\n")
	b.WriteString("-- Range tables are { r16 = { lo, hi, stride, ... }, r32 = { lo, hi, stride, ... } } like\n")
	b.WriteString("-- unicode.RangeTable; fold is the flat list of r, unicode.SimpleFold(r) for every r with\n")
	b.WriteString("-- SimpleFold(r) != r; print/letter/digit are flat lo, hi pairs of unicode.IsPrint/IsLetter/IsDigit.\n")
	b.WriteString("local M = {}\n\n")
	fmt.Fprintf(&b, "M.Version = %s\n", luaString(unicode.Version))
	b.WriteString("\nM.fold = {")
	n := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if f := unicode.SimpleFold(r); f != r {
			if n%8 == 0 {
				b.WriteString("\n   ")
			}
			fmt.Fprintf(&b, " 0x%x, 0x%x,", r, f)
			n++
		}
	}
	b.WriteString("\n}\n")
	writeRanges(&b, "print", unicode.IsPrint)
	writeRanges(&b, "letter", unicode.IsLetter)
	writeRanges(&b, "digit", unicode.IsDigit)
	b.WriteString("\nM.Cn = ")
	writeTable(&b, unicode.Cn)
	b.WriteString("\n")
	writeTables(&b, "Categories", unicode.Categories)
	writeTables(&b, "Scripts", unicode.Scripts)
	writeTables(&b, "FoldCategory", unicode.FoldCategory)
	writeTables(&b, "FoldScript", unicode.FoldScript)
	keys := make([]string, 0, len(unicode.CategoryAliases))
	for k := range unicode.CategoryAliases {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("\nM.CategoryAliases = {\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "    [%s] = %s,\n", luaString(k), luaString(unicode.CategoryAliases[k]))
	}
	b.WriteString("}\n\nreturn M\n")
	if err := os.WriteFile(os.Args[1], []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
