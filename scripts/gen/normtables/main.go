// Command normtables writes the Unicode tables the Lua port needs to emulate
// golang.org/x/text/unicode/norm NFD and unicode.Mn (used by ls/lsutil removeDiacritics).
//
// Usage: go run . <out.lua>
package main

import (
	"fmt"
	"os"
	"strings"
	"unicode"

	"golang.org/x/text/unicode/norm"
)

func main() {
	var b strings.Builder
	b.WriteString("-- Code generated by scripts/gen/normtables from golang.org/x/text/unicode/norm " + norm.Version + " and Go unicode " + unicode.Version + ". DO NOT EDIT.\n")
	b.WriteString("-- decomp: full canonical (NFD) decompositions, except Hangul syllables (algorithmic);\n")
	b.WriteString("-- ccc: non-zero canonical combining classes; mn: unicode.Mn as flat lo, hi, stride triples.\n")
	b.WriteString("local M = {}\n\nM.decomp = {\n")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		if r >= 0xAC00 && r <= 0xD7A3 {
			continue
		}
		s := string(r)
		d := norm.NFD.String(s)
		if d != s {
			fmt.Fprintf(&b, "    [0x%X] = {", r)
			first := true
			for _, x := range d {
				if !first {
					b.WriteString(", ")
				}
				first = false
				fmt.Fprintf(&b, "0x%X", x)
			}
			b.WriteString("},\n")
		}
	}
	b.WriteString("}\n\nM.ccc = {\n")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		if c := norm.NFD.PropertiesString(string(r)).CCC(); c != 0 {
			fmt.Fprintf(&b, "    [0x%X] = %d,\n", r, c)
		}
	}
	b.WriteString("}\n\nM.mn = {\n")
	for _, r := range unicode.Mn.R16 {
		fmt.Fprintf(&b, "    0x%X, 0x%X, %d,\n", r.Lo, r.Hi, r.Stride)
	}
	for _, r := range unicode.Mn.R32 {
		fmt.Fprintf(&b, "    0x%X, 0x%X, %d,\n", r.Lo, r.Hi, r.Stride)
	}
	b.WriteString("}\n\nreturn M\n")
	if err := os.WriteFile(os.Args[1], []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
