local core = require("tslua.core")

describe("core helpers", function()
    it("Len/Append/Slice", function()
        assert.are.equal(0, core.Len(nil))
        assert.are.equal(2, core.Len({ 1, 2 }))
        assert.are.same({ 1 }, core.Append(nil, 1))
        assert.are.same({ 1, 2, 3 }, core.Append({ 1 }, 2, 3))
        assert.are.same({ 2, 3 }, core.Slice({ 1, 2, 3, 4 }, 1, 3))
        assert.are.same({ 3, 4 }, core.Slice({ 1, 2, 3, 4 }, 2))
        assert.are.same({}, core.Slice({ 1, 2 }, 1, 1))
    end)

    it("IntDiv/IntMod truncate like Go", function()
        assert.are.equal(2, core.IntDiv(7, 3))
        assert.are.equal(-2, core.IntDiv(-7, 3))
        assert.are.equal(-2, core.IntDiv(7, -3))
        assert.are.equal(2, core.IntDiv(-7, -3))
        assert.are.equal(1, core.IntMod(7, 3))
        assert.are.equal(-1, core.IntMod(-7, 3))
        assert.are.equal(1, core.IntMod(7, -3))
        assert.are.equal(-1, core.IntMod(-7, -3))
        assert.are.equal(0, core.IntDiv(-1, 2))
    end)

    it("DecodeRune follows utf8.DecodeRuneInString", function()
        assert.are.same({ 0xFFFD, 0 }, { core.DecodeRune("", 0) })
        assert.are.same({ 0x61, 1 }, { core.DecodeRune("abc", 0) })
        assert.are.same({ 0x62, 1 }, { core.DecodeRune("abc", 1) })
        assert.are.same({ 0xE9, 2 }, { core.DecodeRune("\u{E9}", 0) })
        assert.are.same({ 0x20AC, 3 }, { core.DecodeRune("\u{20AC}", 0) })
        assert.are.same({ 0x1F600, 4 }, { core.DecodeRune("x\u{1F600}", 1) })
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeRune("\xff", 0) })
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeRune("\xc3", 0) }) -- truncated
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeRune("\xc0\x80", 0) }) -- overlong
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeRune("\xed\xa0\x80", 0) }) -- surrogate
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeRune("\xf4\x90\x80\x80", 0) }) -- > MaxRune
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeRune("\xe2\x82", 0) })
    end)

    it("DecodeLastRune follows utf8.DecodeLastRuneInString", function()
        assert.are.same({ 0xFFFD, 0 }, { core.DecodeLastRune("") })
        assert.are.same({ 0x63, 1 }, { core.DecodeLastRune("abc") })
        assert.are.same({ 0x1F600, 4 }, { core.DecodeLastRune("a\u{1F600}") })
        assert.are.same({ 0xE9, 2 }, { core.DecodeLastRune("\u{E9}b", 2) })
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeLastRune("a\x80") })
        assert.are.same({ 0xFFFD, 1 }, { core.DecodeLastRune("\xe2\x82") })
    end)

    it("EncodeRune", function()
        assert.are.equal("a", core.EncodeRune(0x61))
        assert.are.equal("\u{E9}", core.EncodeRune(0xE9))
        assert.are.equal("\u{1F600}", core.EncodeRune(0x1F600))
        assert.are.equal("\u{FFFD}", core.EncodeRune(0xD800))
        assert.are.equal("\u{FFFD}", core.EncodeRune(-1))
        assert.are.equal("\u{FFFD}", core.EncodeRune(0x110000))
    end)

    it("StringBuilder", function()
        local b = core.NewStringBuilder()
        assert.are.equal("", b:String())
        b:WriteString("ab")
        b:WriteByte(0x63)
        b:WriteRune(0xE9)
        assert.are.equal("abc\u{E9}", b:String())
        assert.are.equal(5, b:Len())
        b:WriteString("!")
        assert.are.equal("abc\u{E9}!", b:String())
    end)
end)

describe("core.TextRange", function()
    it("has Go's methods", function()
        local r = core.NewTextRange(2, 5)
        assert.are.equal(2, r:Pos())
        assert.are.equal(5, r:End())
        assert.are.equal(3, r:Len())
        assert.is_true(r:Contains(2))
        assert.is_false(r:Contains(5))
        assert.is_true(r:ContainsInclusive(5))
        assert.is_false(r:ContainsExclusive(2))
        assert.are.equal(1, r:WithPos(1):Pos())
        assert.are.equal(2, r.pos) -- immutable
        assert.are.equal(9, r:WithEnd(9):End())
        assert.is_true(r:ContainedBy(core.NewTextRange(0, 5)))
        assert.is_false(r:Overlaps(core.NewTextRange(5, 10)))
        assert.is_true(r:Intersects(core.NewTextRange(5, 10)))
        local u = core.UndefinedTextRange()
        assert.are.equal(-1, u:Pos())
        assert.is_false(u:IsValid())
        assert.is_true(r:IsValid())
        assert.is_true(core.CompareTextRanges(r, core.NewTextRange(2, 6)) < 0)
    end)
end)

describe("core.Tristate", function()
    it("methods", function()
        local T = core.Tristate
        assert.are.equal(T.TSUnknown, T.Unknown)
        assert.are.equal(0, T.TSUnknown)
        assert.is_true(core.Tristate_IsTrue(T.TSTrue))
        assert.is_true(core.Tristate_IsTrueOrUnknown(T.TSUnknown))
        assert.is_true(core.Tristate_IsFalseOrUnknown(T.TSFalse))
        assert.are.equal(T.TSTrue, core.Tristate_DefaultIfUnknown(T.TSUnknown, T.TSTrue))
        assert.are.equal("TSFalse", core.Tristate_String(T.TSFalse))
        assert.are.equal("Tristate(7)", core.Tristate_String(7))
        assert.are.equal("ScriptKindTSX", core.ScriptKind_String(core.ScriptKind.TSX))
        assert.are.equal("ESNext", core.ScriptTarget_String(core.ScriptTarget.ESNext))
        assert.are.equal("NodeNext", core.ModuleKind_String(core.ModuleKind.NodeNext))
        assert.are.equal("react-jsx", core.JsxEmit_String(core.JsxEmit.ReactJSX))
        assert.are.equal("\r\n", core.NewLineKind_GetNewLineCharacter(core.NewLineKind.CRLF))
    end)
end)

describe("core.CompilerOptions", function()
    it("zero values and methods", function()
        local o = core.NewCompilerOptions()
        assert.are.equal(core.Tristate.TSUnknown, o.strict)
        assert.are.equal("", o.outDir)
        assert.are.equal(0, o.target)
        assert.is_nil(o.lib)
        assert.are.equal(core.ScriptTarget.LatestStandard, o:GetEmitScriptTarget())
        assert.are.equal(core.ModuleKind.ES2022, o:GetEmitModuleKind())
        assert.are.equal(core.ModuleResolutionKind.Bundler, o:GetModuleResolutionKind())
        assert.is_true(o:GetStrictOptionValue(o.strictNullChecks))
        local o2 = core.NewCompilerOptions({ module = core.ModuleKind.NodeNext, strict = core.Tristate.TSFalse })
        assert.are.equal(core.ModuleResolutionKind.NodeNext, o2:GetModuleResolutionKind())
        assert.are.equal(core.ModuleDetectionKind.Force, o2:GetEmitModuleDetectionKind())
        assert.is_true(o2:GetResolveJsonModule())
        assert.is_false(o2:GetStrictOptionValue(o2.noImplicitAny))
        local c = o2:Clone()
        assert.are.equal(core.ModuleKind.NodeNext, c.module)
        assert.are_not.equal(o2, c)
        local roots, fromConfig = o:GetEffectiveTypeRoots("/a/b")
        assert.are.same({ "/a/b/node_modules/@types", "/a/node_modules/@types", "/node_modules/@types" }, roots)
        assert.is_false(fromConfig)
        assert.are.equal("", o:GetPathsBasePath("/x"))
    end)
end)

describe("core.go", function()
    it("slice helpers", function()
        local xs = { 1, 2, 3, 4 }
        assert.are.equal(xs, core.Filter(xs, function(x) return x > 0 end))
        assert.are.same({ 2, 4 }, core.Filter(xs, function(x) return x % 2 == 0 end))
        assert.are.same({ 2, 4, 6, 8 }, core.Map(xs, function(x) return x * 2 end))
        assert.is_nil(core.Map(nil, function(x) return x end))
        assert.are.equal(2, core.FindIndex(xs, function(x) return x == 3 end))
        assert.are.equal(-1, core.FindIndex(xs, function(x) return x == 9 end))
        assert.are.equal(0, core.Find(xs, function(x) return x == 9 end))
        assert.are.equal("", core.Find({ "a" }, function(x) return x == "b" end))
        assert.are.same({ 1, 9, 4 }, core.Splice(xs, 1, 2, 9))
        assert.are.same({ 1, 2, 3 }, core.Deduplicate({ 1, 2, 1, 3, 2 }))
        assert.are.same({ 1, 2, 3, 4, 5 }, core.InsertSorted({ 1, 2, 4, 5 }, 3, function(a, b) return a - b end))
        local collected = {}
        for v in core.FilterSeq(xs, function(x) return x > 2 end) do
            collected[#collected + 1] = v
        end
        assert.are.same({ 3, 4 }, collected)
        local pairs_ = {}
        for i, v in core.Enumerate({ "a", "b" }) do
            pairs_[#pairs_ + 1] = i .. v
        end
        assert.are.same({ "0a", "1b" }, pairs_)
        assert.are.same({ 1, 2, 3 }, core.Collect(core.ConcatenateSeq({ 1 }, nil, { 2, 3 })))
    end)

    it("ComputeECMALineStarts", function()
        assert.are.same({ 0 }, core.ComputeECMALineStarts(""))
        assert.are.same({ 0, 2, 5, 7, 11 }, core.ComputeECMALineStarts("a\nb\r\nc\rd\u{2028}e"))
        local line, off = core.PositionToLineAndByteOffset(6, { 0, 2, 5, 7 })
        assert.are.equal(2, line)
        assert.are.equal(1, off)
    end)

    it("UTF16Len", function()
        assert.are.equal(3, core.UTF16Len("abc"))
        assert.are.equal(4, core.UTF16Len("a\u{E9}\u{1F600}"))
    end)

    it("GetSpellingSuggestion", function()
        assert.are.equal("length", core.GetSpellingSuggestionForStrings("lenght", { "foo", "length", "bar" }))
        assert.are.equal("", core.GetSpellingSuggestionForStrings("xyz", { "foo", "bar" }))
        assert.are.equal("Ab", core.GetSpellingSuggestionForStrings("ab", { "Ab", "cd" }))
    end)

    it("GetScriptKindFromFileName", function()
        assert.are.equal(core.ScriptKind.TS, core.GetScriptKindFromFileName("/a/b.MTS"))
        assert.are.equal(core.ScriptKind.JSON, core.GetScriptKindFromFileName("/a/b.json"))
        assert.are.equal(core.ScriptKind.Unknown, core.GetScriptKindFromFileName("/a/b"))
        assert.are.equal(core.ScriptKind.TS, core.EnsureScriptKindFromFileName("/a/b.vue"))
    end)

    it("Pattern", function()
        local p = core.TryParsePattern("foo/*/bar")
        assert.are.equal(4, p.starIndex)
        assert.is_true(p:Matches("foo/x/bar"))
        assert.are.equal("x/y", p:MatchedText("foo/x/y/bar"))
        assert.are.equal(-1, core.TryParsePattern("abc").starIndex)
        assert.is_false(core.TryParsePattern("a*b*").starIndex == -1)
    end)

    it("WorkGroup runs LIFO", function()
        local order = {}
        local wg = core.NewWorkGroup(true)
        wg:Queue(function() order[#order + 1] = 1 end)
        wg:Queue(function() order[#order + 1] = 2 end)
        wg:RunAndWait()
        assert.are.same({ 2, 1 }, order)
    end)
end)
