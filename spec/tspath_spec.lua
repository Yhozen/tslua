describe("TestGetCommonParents", function()
    local opts = {}
    local function run(paths, min)
        return tspath.GetCommonParents(paths, min, tspath.GetPathComponents, opts)
    end
    it("matches Go", function()
        local got, ignored = run({}, 1)
        assert.is_nil(got)
        assert.is_nil(ignored)
        got = run({ "/a/b/c/d" }, 1)
        assert.are.same({ "/a/b/c/d" }, got)
        got, ignored = run({ "/a/b/c/d", "/a/b/c/e", "/a/b/f/g", "/x/y" }, 4)
        assert.are.same({ ["/x/y"] = true }, ignored)
        assert.are.same({ "/a/b/c", "/a/b/f/g" }, got)
        assert.are.same({ "/a/b" }, (run({ "/a/b/c/d", "/a/b/c/e", "/a/b/f/g" }, 1)))
        assert.are.same({ "/" }, (run({ "/a/b/c/d", "/a/b/c/e", "/a/b/f/g", "/x/y/z" }, 1)))
        assert.are.same({ "/a/b", "/x/y/z" }, (run({ "/a/b/c/d", "/a/b/c/e", "/a/b/f/g", "/x/y/z" }, 3)))
        assert.are.same({ "c:/a/b/c/d", "d:/a/b/c/d" }, (run({ "c:/a/b/c/d", "d:/a/b/c/d" }, 1)))
        assert.are.same({ "/a/b/c/d" }, (run({ "/a/b/c/d", "/a/b/c/d" }, 1)))
        assert.are.same({ "/a/b/c/d", "/x/y" }, (run({ "/a/b/c/d", "/x/y" }, 2)))
        assert.are.same({ "/a", "/x/y/z" }, (run({ "/a/b/c/d", "/a/z/c/e", "/a/aaa/f/g", "/x/y/z" }, 2)))
        assert.are.same({ "/a/b" }, (run({ "/a/b/", "/a/b/c" }, 1)))
    end)
end)

