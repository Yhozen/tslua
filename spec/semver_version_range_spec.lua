        bad = { "3.8", "3.9", "4.0" },
    })

    assertRangesGoodBad("<=3.8.0-0", {
        good = { "3.6", "3.7" },
        bad = { "3.8", "3.9", "4.0" },
    })

    -- Big numbers in prerelease strings.
    local lotsaOnes = string.rep("1", 320)
    assertRangesGoodBad(">=1.2.3-1" .. lotsaOnes, {
        good = { "1.2.3-1" .. lotsaOnes, "1.2.3-11" .. lotsaOnes .. ".1", "1.2.3-1" .. lotsaOnes .. ".1+build" },
        bad = { "1.2.3-" .. lotsaOnes .. ".1+build" },
    })
end)

local function assertRangeTest(name, rangeText, versionText, inRange)
    local testName = string.format("%s (version %s in range %s) == %s", name, versionText, rangeText, tostring(inRange))
    it(testName, function()
        local versionRange, ok = semver.TryParseVersionRange(rangeText)
        assert.is_true(ok)
        local version, err = semver.TryParseVersion(versionText)
        assert.is_nil(err)
        assert.are.equal(inRange, versionRange:Test(version))
    end)
end

