local function assertRangesGoodBad(versionRangeString, tests)
    it(versionRangeString, function()
        local versionRange, ok = semver.TryParseVersionRange(versionRangeString)
        assert.is_true(ok)
        for _, good in ipairs(tests.good) do
            local v, err = semver.TryParseVersion(good)
            assert.is_nil(err)
            assert.is_true(versionRange:Test(v), good .. " should be matched by range " .. versionRangeString)
        end

        for _, bad in ipairs(tests.bad) do
            local v, err = semver.TryParseVersion(bad)
            assert.is_nil(err)
            assert.is_true(not versionRange:Test(v), bad .. " should not be matched by range " .. versionRangeString)
        end
    end)
end

