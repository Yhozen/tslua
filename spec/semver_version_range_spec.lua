    })

    assertRangesGoodBad("<3.8.0", {
        good = { "3.6", "3.7" },
        bad = { "3.8", "3.9", "4.0" },
    })

    assertRangesGoodBad("<=3.8.0", {
        good = { "3.6", "3.7", "3.8" },
        bad = { "3.9", "4.0" },
    })
    assertRangesGoodBad(">3.8.0", {
        good = { "3.9", "4.0" },
        bad = { "3.6", "3.7", "3.8" },
    })
    assertRangesGoodBad(">=3.8.0", {
        good = { "3.8", "3.9", "4.0" },
        bad = { "3.6", "3.7" },
    })

    assertRangesGoodBad("<3.8.0-0", {
