        good = { "1.2.3", "1.2.3+build" },
        bad = { "1.2.2", "1.2.4", "1.2.2-pre", "1.2.2+build", "1.2.3-pre" },
    })

    assertRangesGoodBad("1.2.3-pre", {
        good = { "1.2.3-pre", "1.2.3-pre+build.stuff" },
