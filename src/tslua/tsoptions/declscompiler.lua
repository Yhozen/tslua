-- Go reflect.DeepEqual over the option value kinds stored in CompilerOptions.
local function deepEqual(a, b)
    if a == b then
        return true
    end
    if type(a) ~= "table" or type(b) ~= "table" then
        return false
    end
    if getmetatable(a) ~= getmetatable(b) then
        return false
    end
    if tsoptions.isOrderedMap(a) then
        if a:Size() ~= b:Size() then
            return false
        end
        local keysA, valuesA = {}, {}
        for k, v in a:Entries() do
            keysA[#keysA + 1] = k
            valuesA[#valuesA + 1] = v
        end
        local i = 0
        for k, v in b:Entries() do
            i = i + 1
            if keysA[i] ~= k or not deepEqual(valuesA[i], v) then
                return false
            end
        end
        return true
    end
    if #a ~= #b then
        return false
    end
    for k, v in pairs(a) do
        if not deepEqual(v, b[k]) then
            return false
        end
    end
    for k in pairs(b) do
        if a[k] == nil then
            return false
        end
    end
    return true
end

function tsoptions.optionsHaveChanges(oldOptions, newOptions, declFilter)
    if oldOptions == newOptions then
        return false
    end
    if oldOptions == nil or newOptions == nil then
        return true
    end
    return tsoptions.ForEachCompilerOptionValue(newOptions, declFilter, function(option, value, i)
        local newValue = value
        local oldValue = oldOptions[core.CompilerOptions.Fields[i + 1].name]
        if option.strictFlag then
            return oldOptions:GetStrictOptionValue(oldValue) ~= newOptions:GetStrictOptionValue(newValue)
        end
        if option.allowJsFlag then
            return oldOptions:GetAllowJS() ~= newOptions:GetAllowJS()
        end
        return not deepEqual(newValue, oldValue)
    end)
end

-- fn(option, value, i): i is the 0-based index of the field in core.CompilerOptions.Fields.
function tsoptions.ForEachCompilerOptionValue(options, declFilter, fn)
    for i1, field in ipairs(core.CompilerOptions.Fields) do
        local i = i1 - 1
        local optionDeclaration = tsoptions.CommandLineOptionNameMap_Get(tsoptions.CommandLineCompilerOptionsMap, field.name)
        if optionDeclaration ~= nil and declFilter(optionDeclaration) then
            if fn(optionDeclaration, options[field.name], i) then
                return true
            end
        end
    end
    return false
end

function tsoptions.CompilerOptionsAffectSemanticDiagnostics(
    oldOptions,
    newOptions
)
    return tsoptions.optionsHaveChanges(oldOptions, newOptions, function(option)
        return option.affectsSemanticDiagnostics
    end)
end

function tsoptions.CompilerOptionsAffectDeclarationPath(
    oldOptions,
    newOptions
)
    return tsoptions.optionsHaveChanges(oldOptions, newOptions, function(option)
        return option.affectsDeclarationPath
    end)
end

function tsoptions.CompilerOptionsAffectEmit(oldOptions, newOptions)
