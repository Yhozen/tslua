local printer = require("tslua.printer")
local ast = require("tslua.ast")
local core = require("tslua.core")

local Kind = ast.Kind
local SymbolFlags = ast.SymbolFlags

-- Flags enum to track count of temp variables and a few dedicated names (tempFlags)
printer.tempFlagsAuto = 0x00000000 -- No preferred name
printer.tempFlagsCountMask = 0x0FFFFFFF -- Temp variable counter
printer.tempFlags_i = 0x10000000 -- Use/preference flag for '_i'

local NameGenerator = {}
NameGenerator.__index = NameGenerator
printer.NameGenerator = NameGenerator

-- Lua addition: the Go zero value of NameGenerator.
-- Fields: context (*EmitContext), isFileLevelUniqueNameInCurrentFile (function(name, privateName) -> bool),
-- getTextOfNode (function(node) -> string), nodeIdToGeneratedName, nodeIdToGeneratedPrivateName,
-- autoGeneratedIdToGeneratedName, nameGenerationScope, privateNameGenerationScope, generatedNames.
function printer.NewNameGenerator()
    return setmetatable({
        context = nil,
        isFileLevelUniqueNameInCurrentFile = nil,
        getTextOfNode = nil,
        nodeIdToGeneratedName = nil,
        nodeIdToGeneratedPrivateName = nil,
        autoGeneratedIdToGeneratedName = nil,
        nameGenerationScope = nil,
        privateNameGenerationScope = nil,
        generatedNames = printer.newSet(), -- NOTE: Used to match Strada, but should be moved to nameGenerationScope after port is complete.
    }, NameGenerator)
end

-- nameGenerationScope: { next, tempFlags, formattedNameTempFlags, reservedNames }
function printer.newNameGenerationScope(next_)
    return {
        next = next_, -- The next nameGenerationScope in the stack
        tempFlags = 0, -- TempFlags for the current name generation scope.
        formattedNameTempFlags = nil, -- TempFlags for the current name generation scope.
        reservedNames = printer.newSet(), -- Names reserved in nested name generation scopes.
    }
end

function NameGenerator:PushScope(reuseTempVariableScope)
    self.privateNameGenerationScope = printer.newNameGenerationScope(self.privateNameGenerationScope)
    if not reuseTempVariableScope then
        self.nameGenerationScope = printer.newNameGenerationScope(self.nameGenerationScope)
    end
end

function NameGenerator:PopScope(reuseTempVariableScope)
    if self.privateNameGenerationScope ~= nil then
        self.privateNameGenerationScope = self.privateNameGenerationScope.next
    end
    if not reuseTempVariableScope and self.nameGenerationScope ~= nil then
        self.nameGenerationScope = self.nameGenerationScope.next
    end
end

-- Go returns a **nameGenerationScope; in Lua this returns the name of the field holding the scope.
function NameGenerator:getScope(privateName)
    return core.IfElse(privateName, "privateNameGenerationScope", "nameGenerationScope")
end

function NameGenerator:getTempFlags(privateName)
    local scope = self[self:getScope(privateName)]
    if scope ~= nil then
        return scope.tempFlags
    end
    return printer.tempFlagsAuto
end

function NameGenerator:setTempFlags(privateName, flags)
    local key = self:getScope(privateName)
    if self[key] == nil then
        self[key] = printer.newNameGenerationScope(nil)
    end
    self[key].tempFlags = flags
end

-- Gets the TempFlags to use in the current nameGenerationScope for the given key
function NameGenerator:getTempFlagsForFormattedName(privateName, formattedNameKey)
    local scope = self[self:getScope(privateName)]
    if scope ~= nil and scope.formattedNameTempFlags ~= nil then
        local flags = scope.formattedNameTempFlags[formattedNameKey]
        if flags ~= nil then
            return flags
        end
    end
    return printer.tempFlagsAuto
end

-- Sets the TempFlags to use in the current nameGenerationScope for the given key
function NameGenerator:setTempFlagsForFormattedName(privateName, formattedNameKey, flags)
    local key = self:getScope(privateName)
    if self[key] == nil then
        self[key] = printer.newNameGenerationScope(nil)
    end
    local scope = self[key]
    if scope.formattedNameTempFlags == nil then
        scope.formattedNameTempFlags = {}
    end
    scope.formattedNameTempFlags[formattedNameKey] = flags
end

function NameGenerator:reserveName(name, privateName, scoped, temp)
    local key = self:getScope(privateName)
    if self[key] == nil then
        self[key] = printer.newNameGenerationScope(nil)
    end
    if privateName or scoped then
        self[key].reservedNames:Add(name)
    elseif not temp then
        self.generatedNames:Add(name) -- NOTE: Matches Strada, but is incorrect.
        -- (*scope).generatedNames.Add(name) // TODO: generated names should be scoped after Strada port is complete.
    end
end

-- Generate the text for a generated identifier or private identifier
function NameGenerator:GenerateName(name)
    if self.context ~= nil then
        local autoGenerate = self.context.autoGenerate[name]
        if autoGenerate ~= nil then
            if printer.GeneratedIdentifierFlags_IsNode(autoGenerate.flags) then
                -- Node names generate unique names based on their original node
                -- and are cached based on that node's id.
                return self:generateNameForNodeCached(self.context:GetNodeForGeneratedName(name), ast.IsPrivateIdentifier(name), autoGenerate.flags, autoGenerate.prefix or "", autoGenerate.suffix or "")
            else
                -- Auto, Loop, and Unique names are cached based on their unique autoGenerateId.
                if self.autoGeneratedIdToGeneratedName ~= nil then
                    local autoGeneratedName = self.autoGeneratedIdToGeneratedName[autoGenerate.id]
                    if autoGeneratedName ~= nil then
                        return autoGeneratedName
                    end
                end
                if self.autoGeneratedIdToGeneratedName == nil then
                    self.autoGeneratedIdToGeneratedName = {}
                end
                local autoGeneratedName = self:makeName(name)
                self.autoGeneratedIdToGeneratedName[autoGenerate.id] = autoGeneratedName
                return autoGeneratedName
            end
        end
    end
    return self.getTextOfNode(name)
end

function NameGenerator:generateNameForNodeCached(node, privateName, flags, prefix, suffix)
    local nodeId = ast.GetNodeId(node)
    local cacheKey = core.IfElse(privateName, "nodeIdToGeneratedPrivateName", "nodeIdToGeneratedName")
    if self[cacheKey] == nil then
        self[cacheKey] = {}
    end
    local cache = self[cacheKey]

    local cached = cache[nodeId]
    if cached ~= nil then
        return cached
    end

    local name = self:generateNameForNode(node, privateName, flags, prefix, suffix)
    cache[nodeId] = name
    return name
end

function NameGenerator:generateNameForNode(node, privateName, flags, prefix, suffix)
    local kind = node.kind
    if kind == Kind.Identifier or kind == Kind.PrivateIdentifier then
        return self:makeUniqueName(self.getTextOfNode(node), nil --[[checkFn]], printer.GeneratedIdentifierFlags_IsOptimistic(flags), printer.GeneratedIdentifierFlags_IsReservedInNestedScopes(flags), privateName, prefix, suffix)
    elseif kind == Kind.ModuleDeclaration or kind == Kind.EnumDeclaration then
        if privateName or #prefix > 0 or #suffix > 0 then
            error("Generated name for a module or enum cannot be private and may have neither a prefix nor suffix", 0)
        end
        return self:generateNameForModuleOrEnum(node)
    elseif kind == Kind.ImportDeclaration or kind == Kind.JSImportDeclaration or kind == Kind.ExportDeclaration then
        if privateName or #prefix > 0 or #suffix > 0 then
            error("Generated name for an import or export cannot be private and may have neither a prefix nor suffix", 0)
        end
        return self:generateNameForImportOrExportDeclaration(node)
    elseif kind == Kind.FunctionDeclaration or kind == Kind.ClassDeclaration then
        if privateName or #prefix > 0 or #suffix > 0 then
            error("Generated name for a class or function declaration cannot be private and may have neither a prefix nor suffix", 0)
        end
        local name = node:Name()
        if name ~= nil and not (self.context == nil and self.context:HasAutoGenerateInfo(name)) then
            return self:generateNameForNode(name, false --[[privateName]], flags, "" --[[prefix]], "" --[[suffix]])
        end
        return self:generateNameForExportDefault()
    elseif kind == Kind.ExportAssignment then
        if privateName or #prefix > 0 or #suffix > 0 then
            error("Generated name for an export assignment cannot be private and may have neither a prefix nor suffix", 0)
        end
        return self:generateNameForExportDefault()
    elseif kind == Kind.ClassExpression then
        if privateName or #prefix > 0 or #suffix > 0 then
            error("Generated name for a class expression cannot be private and may have neither a prefix nor suffix", 0)
        end
        return self:generateNameForClassExpression()
    elseif kind == Kind.MethodDeclaration or kind == Kind.GetAccessor or kind == Kind.SetAccessor then
        return self:generateNameForMethodOrAccessor(node, privateName, prefix, suffix)
    elseif kind == Kind.ComputedPropertyName then
        return self:makeTempVariableName(printer.tempFlagsAuto, true --[[reservedInNestedScopes]], privateName, prefix, suffix)
    else
        return self:makeTempVariableName(printer.tempFlagsAuto, false --[[reservedInNestedScopes]], privateName, prefix, suffix)
    end
end

function NameGenerator:generateNameForModuleOrEnum(node --[[ ModuleDeclaration | EnumDeclaration ]])
    local name = self.getTextOfNode(node:Name())
    -- Use module/enum name itself if it is unique, otherwise make a unique variation
    if printer.isUniqueLocalName(name, node) then
        return name
    else
        return self:makeUniqueName(name, nil --[[checkFn]], false --[[optimistic]], false --[[scoped]], false --[[privateName]], "" --[[prefix]], "" --[[suffix]])
    end
end

function NameGenerator:generateNameForImportOrExportDeclaration(node --[[ ImportDeclaration | ExportDeclaration ]])
    local expr = ast.GetExternalModuleName(node)
    local baseName = "module"
    if ast.IsStringLiteral(expr) then
        baseName = printer.makeIdentifierFromModuleName(expr:Text())
    end
    return self:makeUniqueName(baseName, nil --[[checkFn]], false --[[optimistic]], false --[[scoped]], false --[[privateName]], "" --[[prefix]], "" --[[suffix]])
end

function NameGenerator:generateNameForExportDefault()
    return self:makeUniqueName("default", nil --[[checkFn]], false --[[optimistic]], false --[[scoped]], false --[[privateName]], "" --[[prefix]], "" --[[suffix]])
end

function NameGenerator:generateNameForClassExpression()
    return self:makeUniqueName("class", nil --[[checkFn]], false --[[optimistic]], false --[[scoped]], false --[[privateName]], "" --[[prefix]], "" --[[suffix]])
end

function NameGenerator:generateNameForMethodOrAccessor(node --[[ MethodDeclaration | AccessorDeclaration ]], privateName, prefix, suffix)
    if ast.IsIdentifier(node:Name()) then
        return self:generateNameForNodeCached(node:Name(), privateName, printer.GeneratedIdentifierFlagsNone, prefix, suffix)
    end
    return self:makeTempVariableName(printer.tempFlagsAuto, false --[[reservedInNestedScopes]], privateName, prefix, suffix)
end

function NameGenerator:makeName(name)
    if self.context ~= nil then
        local autoGenerate = self.context.autoGenerate[name]
        if autoGenerate ~= nil then
            local flags = autoGenerate.flags
            local kind = printer.GeneratedIdentifierFlags_Kind(flags)
            if kind == printer.GeneratedIdentifierFlagsAuto then
                return self:makeTempVariableName(printer.tempFlagsAuto, printer.GeneratedIdentifierFlags_IsReservedInNestedScopes(flags), ast.IsPrivateIdentifier(name), autoGenerate.prefix or "", autoGenerate.suffix or "")
            elseif kind == printer.GeneratedIdentifierFlagsLoop then
                printer.debugAssert(ast.IsIdentifier(name))
                return self:makeTempVariableName(printer.tempFlags_i, printer.GeneratedIdentifierFlags_IsReservedInNestedScopes(flags), false --[[privateName]], autoGenerate.prefix or "", autoGenerate.suffix or "")
            elseif kind == printer.GeneratedIdentifierFlagsUnique then
                return self:makeUniqueName(
                    name:Text(),
                    core.IfElse(printer.GeneratedIdentifierFlags_IsFileLevel(flags), self.isFileLevelUniqueNameInCurrentFile, nil),
                    printer.GeneratedIdentifierFlags_IsOptimistic(flags),
                    printer.GeneratedIdentifierFlags_IsReservedInNestedScopes(flags),
                    ast.IsPrivateIdentifier(name),
                    autoGenerate.prefix or "",
                    autoGenerate.suffix or ""
                )
            end
        end
    end
    return self.getTextOfNode(name)
end

-- Return the next available name in the pattern _a ... _z, _0, _1, ...
-- TempFlags._i may be used to express a preference for that dedicated name.
-- Note that names generated by makeTempVariableName and makeUniqueName will never conflict.
function NameGenerator:makeTempVariableName(flags, reservedInNestedScopes, privateName, prefix, suffix)
    local tempFlags
    local key = ""
    local simple = #prefix == 0 and #suffix == 0
    if simple then
        tempFlags = self:getTempFlags(privateName)
    else
        -- Generate a key to use to acquire a TempFlags counter based on the fixed portions of the generated name.
        key = printer.FormatGeneratedName(privateName, prefix, "" --[[base]], suffix)
        if privateName then
            key = printer.ensureLeadingHash(key)
        end
        tempFlags = self:getTempFlagsForFormattedName(privateName, key)
    end

    if flags ~= 0 and tempFlags & flags == 0 then
        local fullName = printer.FormatGeneratedName(privateName, prefix, "_i", suffix)
        if self:isUniqueName(fullName, privateName) then
            tempFlags = tempFlags | flags
            self:reserveName(fullName, privateName, reservedInNestedScopes, true --[[temp]])
            if simple then
                self:setTempFlags(privateName, tempFlags)
            else
                self:setTempFlagsForFormattedName(privateName, key, tempFlags)
            end
            return fullName
        end
    end

    while true do
        local count = tempFlags & printer.tempFlagsCountMask
        tempFlags = tempFlags + 1
        -- Skip over 'i' and 'n'
        if count ~= 8 and count ~= 13 then
            local name
            if count < 26 then
                name = "_" .. string.char(0x61 + count)
            else
                name = "_" .. string.format("%d", count - 26)
            end
            local fullName = printer.FormatGeneratedName(privateName, prefix, name, suffix)
            if self:isUniqueName(fullName, privateName) then
                self:reserveName(fullName, privateName, reservedInNestedScopes, true --[[temp]])
                if simple then
                    self:setTempFlags(privateName, tempFlags)
                else
                    self:setTempFlagsForFormattedName(privateName, key, tempFlags)
                end
                return fullName
            end
        end
    end
end

-- Generate a name that is unique within the current file and doesn't conflict with any names
-- in global scope. The name is formed by adding an '_n' suffix to the specified base name,
-- where n is a positive integer. Note that names generated by makeTempVariableName and
-- makeUniqueName are guaranteed to never conflict.
-- If `optimistic` is set, the first instance will use 'baseName' verbatim instead of 'baseName_1'
function NameGenerator:makeUniqueName(baseName, checkFn, optimistic, scoped, privateName, prefix, suffix)
    baseName = printer.removeLeadingHash(baseName)
    if optimistic then
        local fullName = printer.FormatGeneratedName(privateName, prefix, baseName, suffix)
        if self:checkUniqueName(fullName, privateName, checkFn) then
            self:reserveName(fullName, privateName, scoped, false --[[temp]])
            return fullName
        end
    end

    -- Find the first unique 'name_n', where n is a positive integer
    if #baseName > 0 and string.byte(baseName, #baseName) ~= 0x5F then -- '_'
        baseName = baseName .. "_"
    end

    local i = 1
    while true do
        local fullName = printer.FormatGeneratedName(privateName, prefix, baseName .. string.format("%d", i), suffix)
        if self:checkUniqueName(fullName, privateName, checkFn) then
            self:reserveName(fullName, privateName, scoped, false --[[temp]])
            return fullName
        end
        i = i + 1
    end
end

function NameGenerator:MakeFileLevelOptimisticUniqueName(name)
    return self:makeUniqueName(name, self.isFileLevelUniqueNameInCurrentFile, true --[[optimistic]], false --[[scoped]], false --[[privateName]], "" --[[prefix]], "" --[[suffix]])
end

function NameGenerator:checkUniqueName(name, privateName, checkFn)
    if checkFn ~= nil then
        return checkFn(name, privateName)
    else
        return self:isUniqueName(name, privateName)
    end
end

function printer.nextContainer(node)
    local data = node:LocalsContainerData()
    if data ~= nil then
        return data.nextContainer
    end
    return nil
end

function printer.isUniqueLocalName(name, container)
    local node = container
    while node ~= nil and ast.IsNodeDescendantOf(node, container) and node:LocalsContainerData() ~= nil do
        local locals = node:Locals()
        if locals ~= nil then
            -- We conservatively include alias symbols to cover cases where they're emitted as locals
            local loc = locals[name]
            if loc ~= nil and loc.flags & (SymbolFlags.Value | SymbolFlags.ExportValue | SymbolFlags.Alias) ~= 0 then
                return false
            end
        end
        node = printer.nextContainer(node)
    end
    return true
end

function NameGenerator:isUniqueName(name, privateName)
    return (self.isFileLevelUniqueNameInCurrentFile == nil or self.isFileLevelUniqueNameInCurrentFile(name, privateName)) and
        not self:isReservedName(name, privateName)
end

function NameGenerator:isReservedName(name, privateName)
    local scope = self[self:getScope(privateName)]

    -- NOTE: The following matches Strada, but is incorrect.
    if self.generatedNames:Has(name) then
        return true
    end

    -- TODO: generated names should be scoped after Strada port is complete.
    ----if *scope != nil {
    ----	if (*scope).generatedNames.Has(name) {
    ----		return true
    ----	}
    ----}

    while scope ~= nil do
        if scope.reservedNames:Has(name) then
            return true
        end
        scope = scope.next
    end
    return false
end
